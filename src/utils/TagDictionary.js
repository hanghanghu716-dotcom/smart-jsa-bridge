// ✅ [복합 매칭 알고리즘] 의미론적(Semantic) 분석을 통해 누락된 태그 추론
const applyComplexSemanticRules = (text, tags) => {
  // 1. 호흡용보호구 추론 (위험인자 + 포괄어)
  if (/(세라크울|석면|분진|흄|fume|유기용제|흡입|질식|유해가스|화학물질|페인트|도장)/.test(text) && 
      /(보호구|마스크|방독면|착용|지급)/.test(text)) {
    tags.add("보호구(방독/방진마스크)");
  }

  // 2. 추락방지 추론
  if (/(고소|단부|비계|지붕|개구부|추락|떨어짐|높은곳)/.test(text) && 
      /(보호구|안전대|생명줄|안전블록|착용|체결)/.test(text)) {
    tags.add("보호구(안전대)");
  }

  // 3. TBM/교육 추론
  if (/(작업 전|시작 전|투입 전|사전)/.test(text) && /(교육|조회|미팅|회의|공유|전파)/.test(text)) {
    tags.add("관리(작업전TBM)");
  }

  // 4. LOTO 추론
  if (/(정전|전원 차단|밸브 차단|동력 차단)/.test(text) && /(잠금|시건|표지판|tag|loto)/.test(text)) {
    tags.add("준비(에너지차단)");
  }

  // 5. 정리정돈/마무리 추론
  if (/(작업 후|종료 후|마무리|완료)/.test(text) && /(정리|정돈|청소|수거|폐기물)/.test(text)) {
    tags.add("마무리(정리정돈)");
  }
};

// ✅ [메인 함수] 텍스트 기반 자동 태그 추출기
export const extractAutoTagsFromJSA = (projectName, analysisData) => {
  // 전처리: 텍스트 병합 및 정규화
  const combinedContent = (projectName + " " + JSON.stringify(analysisData)).toLowerCase();
  const tags = new Set();

  // 1단계: 300종 키워드 맵 순회 매칭
  Object.entries(DIMENSIONAL_KEYWORD_MAP).forEach(([tag, keywords]) => {
    if (keywords.some(kw => combinedContent.includes(kw))) {
      tags.add(tag);
    }
  });

  // 2단계: 복합 매칭 룰셋 적용
  applyComplexSemanticRules(combinedContent, tags);

  return Array.from(tags);
};